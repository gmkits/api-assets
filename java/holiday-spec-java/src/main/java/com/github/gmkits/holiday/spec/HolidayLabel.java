package com.github.gmkits.holiday.spec;

/**
 * 中国节假日数据中使用的常见节日标签。
 */
public enum HolidayLabel {

    /** 元旦（1 月 1 日）。 */
    NEW_YEAR,

    /** 春节。 */
    SPRING_FESTIVAL,

    /** 清明节。 */
    TOMB_SWEEPING,

    /** 劳动节（5 月 1 日）。 */
    LABOUR_DAY,

    /** 端午节。 */
    DRAGON_BOAT,

    /** 中秋节。 */
    MID_AUTUMN,

    /** 国庆节（10 月 1 日）。 */
    NATIONAL_DAY
}
